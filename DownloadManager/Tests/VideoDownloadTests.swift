    // MARK: - Download Options Tests
    
    func testDefaultOptions() {
        let options = VideoDownloadOptions.default
        
        XCTAssertEqual(options.quality, .quality1080p)
        XCTAssertEqual(options.format, .mp4)
        XCTAssertFalse(options.downloadSubtitles)
        XCTAssertTrue(options.embedThumbnail)
        XCTAssertFalse(options.extractAudioOnly)
    }
    
    func testAudioOnlyOptions() {
        let options = VideoDownloadOptions.audioOnly
        
        XCTAssertEqual(options.format, .mp3)
        XCTAssertTrue(options.extractAudioOnly)
        XCTAssertFalse(options.downloadSubtitles)
    }
    
    func testHighQualityOptions() {
        let options = VideoDownloadOptions.highQuality
        
        XCTAssertEqual(options.quality, .quality4K)
        XCTAssertEqual(options.preferredCodec, .h265)
        XCTAssertTrue(options.downloadSubtitles)
        XCTAssertEqual(options.fps, 60)
    }
    
    // MARK: - Task Tests
    
    func testVideoDownloadTaskCreation() {
        let url = URL(string: "https://www.youtube.com/watch?v=test")!
        let task = VideoDownloadTask(url: url)
        
        XCTAssertEqual(task.url, url)
        XCTAssertEqual(task.platform, .youtube)
        XCTAssertEqual(task.state, .pending)
        XCTAssertEqual(task.progress, 0.0)
        XCTAssertNotNil(task.id)
    }
    
    func testTaskWithCustomOptions() {
        let url = URL(string: "https://vimeo.com/123")!
        let options = VideoDownloadOptions(
            quality: .quality4K,
            format: .mkv,
            downloadSubtitles: true,
            selectedSubtitleLanguages: ["en", "es"],
            embedThumbnail: false,
            convertToFormat: nil,
            extractAudioOnly: false,
            preferredCodec: .vp9,
            fps: 60,
            maxFileSize: nil
        )
        
        let task = VideoDownloadTask(url: url, options: options)
        
        XCTAssertEqual(task.platform, .vimeo)
        XCTAssertEqual(task.options.quality, .quality4K)
        XCTAssertEqual(task.options.format, .mkv)
        XCTAssertTrue(task.options.downloadSubtitles)
    }
    
    func testTaskSpeedFormatting() {
        let task = VideoDownloadTask(url: URL(string: "https://example.com/video")!)
        task.speed = 1_500_000 // 1.5 MB/s
        
        XCTAssertTrue(task.formattedSpeed.contains("MB"))
    }
    
    // MARK: - Statistics Tests
    
    func testStatisticsInitialization() {
        let stats = VideoDownloadStatistics()
        
        XCTAssertEqual(stats.totalVideosDownloaded, 0)
        XCTAssertEqual(stats.totalAudioExtracted, 0)
        XCTAssertEqual(stats.totalPlaylistsDownloaded, 0)
        XCTAssertEqual(stats.successRate, 0)
    }
    
    func testRecordVideoSuccess() {
        var stats = VideoDownloadStatistics()
        
        let task = VideoDownloadTask(url: URL(string: "https://youtube.com/test")!)
        stats.recordSuccess(task: task, bytesDownloaded: 50_000_000, duration: 120)
        
        XCTAssertEqual(stats.totalVideosDownloaded, 1)
        XCTAssertEqual(stats.totalAudioExtracted, 0)
        XCTAssertEqual(stats.totalDataDownloaded, 50_000_000)
        XCTAssertEqual(stats.downloadsByPlatform[.youtube], 1)
    }
    
    func testRecordAudioSuccess() {
        var stats = VideoDownloadStatistics()
        
        var task = VideoDownloadTask(url: URL(string: "https://youtube.com/test")!)
        task.options.extractAudioOnly = true
        
        stats.recordSuccess(task: task, bytesDownloaded: 5_000_000, duration: 60)
        
        XCTAssertEqual(stats.totalVideosDownloaded, 0)
        XCTAssertEqual(stats.totalAudioExtracted, 1)
    }
    
    func testRecordFailure() {
        var stats = VideoDownloadStatistics()
        
        stats.recordFailure()
        stats.recordFailure()
        
        XCTAssertEqual(stats.failureCount, 2)
    }
    
    func testSuccessRateCalculation() {
        var stats = VideoDownloadStatistics()
        
        let task1 = VideoDownloadTask(url: URL(string: "https://youtube.com/1")!)
        stats.recordSuccess(task: task1, bytesDownloaded: 10_000_000, duration: 60)
        
        let task2 = VideoDownloadTask(url: URL(string: "https://youtube.com/2")!)
        stats.recordSuccess(task: task2, bytesDownloaded: 10_000_000, duration: 60)
        
        stats.recordFailure()
        
        // 2 successes out of 3 total = 66.67%
        XCTAssertEqual(stats.successRate, 200.0 / 3.0, accuracy: 0.1)
    }
    
    func testAverageDownloadTime() {
        var stats = VideoDownloadStatistics()
        
        let task1 = VideoDownloadTask(url: URL(string: "https://youtube.com/1")!)
        stats.recordSuccess(task: task1, bytesDownloaded: 10_000_000, duration: 60)
        
        let task2 = VideoDownloadTask(url: URL(string: "https://youtube.com/2")!)
        stats.recordSuccess(task: task2, bytesDownloaded: 10_000_000, duration: 120)
        
        XCTAssertEqual(stats.averageDownloadTime, 90.0) // (60 + 120) / 2
    }
    
    // MARK: - Manager Tests
    
    func testAddVideoDownload() {
        let url = URL(string: "https://www.youtube.com/watch?v=test")!
        let task = manager.addVideoDownload(url: url)
        
        XCTAssertTrue(manager.videoTasks.contains(where: { $0.id == task.id }))
        XCTAssertEqual(task.url, url)
    }
    
    func testRemoveTask() {
        let url = URL(string: "https://www.youtube.com/watch?v=test")!
        let task = manager.addVideoDownload(url: url)
        
        XCTAssertEqual(manager.videoTasks.count, 1)
        
        manager.removeTask(task)
        
        XCTAssertEqual(manager.videoTasks.count, 0)
    }
    
    func testMetadataFetching() async {
        let url = URL(string: "https://www.youtube.com/watch?v=test")!
        let task = VideoDownloadTask(url: url)
        
        await manager.fetchMetadata(for: task)
        
        XCTAssertNotNil(task.metadata)
        XCTAssertEqual(task.state, .ready)
    }
    
    func testPlaylistDetection() async {
        let url = URL(string: "https://www.youtube.com/playlist?list=PLtest")!
        let task = VideoDownloadTask(url: url)
        
        await manager.fetchMetadata(for: task)
        
        XCTAssertTrue(task.metadata?.isPlaylist ?? false)
    }
    
    // MARK: - Integration Tests
    
    func testFullDownloadWorkflow() async {
        let url = URL(string: "https://www.youtube.com/watch?v=test")!
        let task = manager.addVideoDownload(url: url)
        
        // Should start in pending state
        XCTAssertEqual(task.state, .pending)
        
        // Metadata should be fetched
        try? await Task.sleep(nanoseconds: 2_000_000_000)
        XCTAssertNotNil(task.metadata)
    }
    
    func testMultiplePlatforms() {
        let youtubeURL = URL(string: "https://www.youtube.com/watch?v=1")!
        let vimeoURL = URL(string: "https://vimeo.com/123")!
        let dailymotionURL = URL(string: "https://www.dailymotion.com/video/x123")!
        
        let task1 = manager.addVideoDownload(url: youtubeURL)
        let task2 = manager.addVideoDownload(url: vimeoURL)
        let task3 = manager.addVideoDownload(url: dailymotionURL)
        
        XCTAssertEqual(task1.platform, .youtube)
        XCTAssertEqual(task2.platform, .vimeo)
        XCTAssertEqual(task3.platform, .dailymotion)
    }
    
    func testCancelDownload() {
        let url = URL(string: "https://www.youtube.com/watch?v=test")!
        let task = manager.addVideoDownload(url: url)
        
        manager.cancelDownload(task)
        
        XCTAssertEqual(task.state, .cancelled)
        XCTAssertNotNil(task.error)
    }
    
